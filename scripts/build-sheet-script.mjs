#!/usr/bin/env node
// ── build-sheet-script — the registration sheet's clean-up script ────────────
//
// Writes docs/registration-sheet.gs: a Google Apps Script you paste into the
// registration form's responses sheet (Extensions → Apps Script). It keeps
// one row per masjid — see tidyPlan in src/lib/registrations.js — checking
// every row's signature with the same code the screens use, so a row sent by
// anyone else can never replace a masjid's settings.
//
//   npm run build:sheet-script
//
// Run it again after changing src/lib/registrations.js or
// src/lib/signatures.js, and commit the result
// (src/lib/__tests__/registrationSheetScript.test.js checks it's current).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

// The same output whoever runs it (the tests run it with NODE_ENV=test).
process.env.NODE_ENV = 'production';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'docs/registration-sheet.gs');

const HEADER = `/**
 * Prayer Times TV — registration sheet clean-up
 * ==============================================
 * Keeps one row per masjid in this sheet (the registration form's
 * responses):
 *   - an approved masjid keeps its approved row, still ticked, with its
 *     newest signed settings copied in; its other rows are removed;
 *   - a newer request under a different publish key (a masjid registering
 *     again after losing its passphrase — or someone else) stays until you
 *     tick it or delete it;
 *   - a masjid waiting for approval keeps its newest row;
 *   - rows that aren't validly signed (tests, junk, anything edited by hand)
 *     are removed.
 * Every row's signature is checked with the same code the screens use, so
 * rows anyone sends to the form can never replace a masjid's settings.
 *
 * Install (once): Extensions → Apps Script, replace everything in Code.gs
 * with this file, save, and reload the sheet. Then Masjids → "Tidy
 * automatically after each response" and allow it (Google warns that it
 * hasn't verified the script, because it's your own: Advanced → Go to …).
 * Masjids → "Tidy now" tidies at any time.
 *
 * Generated by scripts/build-sheet-script.mjs from src/lib/registrations.js
 * and src/lib/signatures.js, with tweetnacl (public domain). Don't edit it
 * here: change those files and run \`npm run build:sheet-script\`.
 */

/** @OnlyCurrentDoc */
`;

const GLUE = `
/** Adds the Masjids menu when the sheet opens. */
function onOpen() {
  SpreadsheetApp.getUi()
    .createMenu('Masjids')
    .addItem('Tidy now', 'tidyNow')
    .addItem('Tidy automatically after each response', 'installAutoTidy')
    .addToUi();
}

/** Run once: tidies the sheet after every form response from now on. */
function installAutoTidy() {
  const ss = SpreadsheetApp.getActive();
  for (const trigger of ScriptApp.getProjectTriggers()) {
    if (trigger.getHandlerFunction() === 'tidyAfterResponse') ScriptApp.deleteTrigger(trigger);
  }
  ScriptApp.newTrigger('tidyAfterResponse').forSpreadsheet(ss).onFormSubmit().create();
  return tidyNow();
}

/** The form-submit trigger. */
function tidyAfterResponse() {
  return tidy_();
}

/** Masjids → Tidy now. */
function tidyNow() {
  const result = tidy_();
  const s = result.summary;
  const message = result.ok
    ? s.approved + ' approved masjid(s), ' + s.waiting + ' waiting for approval, ' +
      s.pending + ' new request(s) to check; ' + s.removed + ' row(s) removed.'
    : "Nothing changed: this sheet's first tab doesn't have the columns " +
      'Timestamp, Masjid code, Settings and Publish key.';
  SpreadsheetApp.getActive().toast(message, 'Masjids', 10);
  return result;
}

function tidy_() {
  const lock = LockService.getScriptLock();
  lock.waitLock(30000);
  try {
    // The first tab: the one the screens read.
    const sheet = SpreadsheetApp.getActive().getSheets()[0];
    const plan = MasjidSheet.plan(sheet.getDataRange().getValues());
    if (!plan.ok) return plan;
    for (const update of plan.updates) {
      for (const [col, value] of update.cells) {
        sheet.getRange(update.row + 1, col + 1).setValue(value);
      }
    }
    // Highest first, so the rows above keep their places. A sheet must keep
    // one row below its frozen header: the last one is emptied instead.
    for (const row of plan.deletes) {
      if (sheet.getMaxRows() - sheet.getFrozenRows() > 1) sheet.deleteRow(row + 1);
      else sheet.getRange(row + 1, 1, 1, sheet.getLastColumn()).clearContent();
    }
    return plan;
  } finally {
    lock.releaseLock();
  }
}
`;

const output = await build({
  configFile: false,
  root,
  mode: 'production',
  logLevel: 'warn',
  build: {
    write: false,
    minify: false,
    target: 'es2019',
    lib: {
      entry: path.join(root, 'scripts/sheet-script/tidy-entry.js'),
      formats: ['iife'],
      name: 'MasjidSheet',
      fileName: () => 'registration-sheet.js',
    },
  },
});
const bundle = (Array.isArray(output) ? output[0] : output).output[0].code;
const script = `${HEADER}\n${bundle.trim()}\n${GLUE}`;

// --check: only say whether the committed file is current (for the tests).
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile)
    ? fs.readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n')
    : '';
  if (current !== script) {
    console.error(`${path.relative(root, outFile)} is out of date: run npm run build:sheet-script`);
    process.exit(1);
  }
  console.log(`${path.relative(root, outFile)} is current`);
} else {
  fs.writeFileSync(outFile, script);
  console.log(`Wrote ${path.relative(root, outFile)} (${Math.round(script.length / 1024)} KB)`);
}
