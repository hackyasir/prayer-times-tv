#!/usr/bin/env node
// ── build-sheet-script — the registration sheet's clean-up script ────────────
//
// Writes docs/registration-sheet.gs: a Google Apps Script you paste into the
// registration form's responses sheet (Extensions → Apps Script). It keeps
// one row per masjid — see tidyPlan in src/lib/registrations.js — checking
// every row's signature with the same rules the screens use, so a row sent by
// anyone else can never replace a masjid's settings.
//
//   npm run build:sheet-script
//
// Run it again after changing src/lib/registrations.js or
// src/lib/signatures.js, and commit the result
// (src/lib/__tests__/registrationSheetScript.test.js checks it's current).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'vite';

// The same output whoever runs it (the tests run it with NODE_ENV=test).
process.env.NODE_ENV = 'production';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'docs/registration-sheet.gs');

const HEADER = `/**
 * Prayer Times TV — registration sheet clean-up
 * ==============================================
 * Keeps one row per masjid in this sheet (the registration form's
 * responses):
 *   - an approved masjid keeps its approved row, still ticked, with its
 *     newest signed settings copied in; its other rows are removed;
 *   - newer requests under a different publish key (a masjid registering
 *     again after losing its passphrase — or someone else) stay until you
 *     tick or delete them (the newest five keys);
 *   - a masjid waiting for approval keeps its newest row (newest five keys);
 *   - each key you ticked keeps one ticked row (copies go);
 *   - other rows that aren't validly signed (tests, junk, anything edited by
 *     hand) are removed;
 *   - empty rows stay (with their checkboxes); a tick on one is cleared.
 * Every row's signature is checked with the same rules the screens use, so
 * rows anyone sends to the form can never replace a masjid's settings.
 * After each response only that masjid's rows are tidied; the whole sheet
 * is tidied once a day, and whenever you choose Masjids → "Tidy now".
 *
 * Install (once, and again after pasting a newer version): Extensions →
 * Apps Script, replace everything in Code.gs with this file, save, and
 * reload the sheet. Then Masjids → "Tidy automatically" and allow it
 * (Google warns that it hasn't verified the script, because it's your own:
 * Advanced → Go to …).
 *
 * Generated by scripts/build-sheet-script.mjs from src/lib/registrations.js
 * and src/lib/signatures.js, with tweetnacl's reference build, nacl.js
 * (public domain). Don't edit it here: change those files and run
 * \`npm run build:sheet-script\`.
 */

/** @OnlyCurrentDoc */
`;

const GLUE = `
/** Adds the Masjids menu when the sheet opens. */
function onOpen() {
  SpreadsheetApp.getUi()
    .createMenu('Masjids')
    .addItem('Tidy now', 'tidyNow')
    .addItem('Tidy automatically', 'installAutoTidy')
    .addToUi();
}

/**
 * Run once: from now on, tidies the masjid's rows after each form response,
 * and the whole sheet once a day. Only adds what's missing, so running it
 * again (say, after pasting a newer version) is safe: deleting and
 * re-creating triggers is where Google's servers most often fail.
 */
function installAutoTidy() {
  const ss = SpreadsheetApp.getActive();
  const triggers = [
    ['tidy after each response', 'tidyAfterResponse',
      () => ScriptApp.newTrigger('tidyAfterResponse').forSpreadsheet(ss).onFormSubmit().create()],
    ['daily tidy', 'tidyDaily',
      () => ScriptApp.newTrigger('tidyDaily').timeBased().everyDays(1).atHour(3).create()],
  ];
  for (const [what, handler, create] of triggers) {
    try {
      // Looked up again on each try, so a retry never adds a second one.
      withRetry_(() => {
        const exists = ScriptApp.getProjectTriggers()
          .some((t) => t.getHandlerFunction() === handler);
        if (!exists) create();
      });
    } catch (err) {
      return report_("Couldn't set up the " + what, err);
    }
  }
  return tidyNow();
}

/**
 * fn(), tried up to three times when Google reports a passing error ("We're
 * sorry, a server error occurred…"). Anything else is thrown straight away.
 */
function withRetry_(fn) {
  for (let attempt = 1; ; attempt++) {
    try {
      return fn();
    } catch (err) {
      const passing = /server error|service error|timed out|internal error|try again/i;
      if (attempt >= 3 || !passing.test(String((err && err.message) || err))) throw err;
      Utilities.sleep(2000 * attempt);
    }
  }
}

/**
 * Says what didn't work, with a short reference; the details go to the
 * script's log (Extensions → Apps Script → Executions).
 */
function report_(what, err) {
  const ref = Utilities.getUuid().slice(0, 8);
  console.error(what + ' (ref ' + ref + '): ' + ((err && err.stack) || err));
  SpreadsheetApp.getActive().toast(
    what + '. Wait a minute and try again (ref ' + ref + ').', 'Masjids', 20);
  return { ok: false, reason: 'error', ref: ref };
}

/**
 * The form-submit trigger: only the masjid the response is for, so each
 * response checks a few signatures rather than every row's. A response
 * without a usable code waits for the daily tidy (screens never read it).
 */
function tidyAfterResponse(e) {
  if (!e || !e.namedValues) return tidy_();
  // A code that isn't usable still tidies empty rows and the response's tick.
  return tidy_(MasjidSheet.responseCode(e.namedValues) || '', e.namedValues);
}

/** The daily trigger: the whole sheet, for anything a response run missed. */
function tidyDaily() {
  return tidy_();
}

/** Masjids → Tidy now. */
function tidyNow() {
  let result;
  try {
    result = tidy_();
  } catch (err) {
    return report_("Couldn't tidy the sheet", err);
  }
  const s = result.summary;
  const message = result.ok
    ? s.approved + ' approved masjid(s), ' + s.waiting + ' waiting for approval, ' +
      s.pending + ' new request(s) to check; ' + s.removed + ' row(s) removed.' +
      (s.unverified
        ? ' ' + s.unverified + " ticked row(s) aren't validly signed (edited by hand?); " +
          'they were left as they are.'
        : '') +
      (s.cleared ? ' ' + s.cleared + ' empty row(s) unticked.' : '') +
      (result.stopped
        ? ' The sheet changed while it was being tidied, so it stopped: choose Tidy now again.'
        : '') +
      (result.summary.partial
        ? ' Not every row was checked this time; the rest are checked on the next run.'
        : '')
    : "Nothing changed: this sheet's first tab doesn't have the columns " +
      'Timestamp, Masjid code, Settings and Publish key.';
  SpreadsheetApp.getActive().toast(message, 'Masjids', 10);
  return result;
}

/** A value to write as it is: text starting with = + - @, a tab or a return stays text. */
function asText_(value) {
  return typeof value === 'string' && /^[=+\\-@\\t\\r]/.test(value) ? "'" + value : value;
}

/** Comparable text for a row's values (dates by their time). */
function rowKey_(values) {
  return JSON.stringify(values.map((v) => (v instanceof Date ? v.getTime() : v)));
}

/**
 * Tidies the first tab (the one the screens read): one masjid, or all.
 * A try that fails partway is safe to repeat: each one reads the sheet
 * again and works out what's still to do.
 */
function tidy_(code, response) {
  return withRetry_(() => tidyOnce_(code, response));
}

/** Stop checking signatures after this long; the rest waits for the next run. */
const BUDGET_MS = 4 * 60 * 1000;

function tidyOnce_(code, response) {
  const lock = LockService.getScriptLock();
  lock.waitLock(30000);
  try {
    const sheet = SpreadsheetApp.getActive().getSheets()[0];
    const values = sheet.getDataRange().getValues();
    // A response that arrives already ticked went into a row ticked by
    // mistake: you can't have approved it yet, so the tick goes.
    if (response) {
      const ticked = MasjidSheet.tickedResponse(values, response);
      if (ticked.row > 0) {
        sheet.getRange(ticked.row + 1, ticked.col + 1).setValue(false);
        values[ticked.row][ticked.col] = false;
      }
    }
    const plan = MasjidSheet.plan(values, code, { budgetMs: BUDGET_MS });
    if (!plan.ok) return plan;
    // Each row is checked before it's changed: if someone sorted or inserted
    // rows while this ran, it stops rather than change the wrong one.
    const unchanged = (row) =>
      rowKey_(sheet.getRange(row + 1, 1, 1, values[row].length).getValues()[0]) ===
      rowKey_(values[row]);
    for (const update of plan.updates) {
      if (!unchanged(update.row)) {
        plan.stopped = true;
        return plan;
      }
      for (const [col, value] of update.cells) {
        // A name or city is written as text, never run as a formula.
        sheet.getRange(update.row + 1, col + 1).setValue(asText_(value));
      }
    }
    // Highest first, so the rows above keep their places. A sheet must keep
    // one row below its frozen header: the last one is emptied instead.
    for (const row of plan.deletes) {
      if (!unchanged(row)) {
        plan.stopped = true;
        break;
      }
      if (sheet.getMaxRows() - sheet.getFrozenRows() > 1) sheet.deleteRow(row + 1);
      else sheet.getRange(row + 1, 1, 1, sheet.getLastColumn()).clearContent();
    }
    return plan;
  } finally {
    lock.releaseLock();
  }
}
`;

const output = await build({
  configFile: false,
  root,
  mode: 'production',
  logLevel: 'warn',
  // tweetnacl's reference build (nacl.js) instead of its speed-optimised one
  // (nacl-fast.js, which the screens use): the same library, version and
  // Ed25519 checks in about half the lines. It's slower per signature, but
  // each run after a form response checks only a few.
  resolve: { alias: [{ find: /^tweetnacl$/, replacement: 'tweetnacl/nacl.js' }] },
  build: {
    write: false,
    minify: false,
    target: 'es2019',
    lib: {
      entry: path.join(root, 'scripts/sheet-script/tidy-entry.js'),
      formats: ['iife'],
      name: 'MasjidSheet',
      fileName: () => 'registration-sheet.js',
    },
  },
});
const bundle = (Array.isArray(output) ? output[0] : output).output[0].code;
const script = `${HEADER}\n${bundle.trim()}\n${GLUE}`;

// --check: only say whether the committed file is current (for the tests).
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile)
    ? fs.readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n')
    : '';
  if (current !== script) {
    console.error(`${path.relative(root, outFile)} is out of date: run npm run build:sheet-script`);
    process.exit(1);
  }
  console.log(`${path.relative(root, outFile)} is current`);
} else {
  fs.writeFileSync(outFile, script);
  console.log(`Wrote ${path.relative(root, outFile)} (${Math.round(script.length / 1024)} KB)`);
}
